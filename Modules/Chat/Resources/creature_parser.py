#!/usr/bin/env python3
"""Generate flavor-specific creature-name lookup tables from Wago CSV exports."""

import argparse
import csv
from pathlib import Path


HERE = Path(__file__).resolve().parent
EXPORTS = {
    "retail": ("Creature.12.1.5.csv", "CreatureDataRetail.lua"),
    "forever": ("Creature.1.60.1.csv", "CreatureDataForever.lua"),
}
REQUIRED_COLUMNS = {"ID", "Name_lang", "DisplayID_0"}


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def generate(flavor: str) -> None:
    csv_name, lua_name = EXPORTS[flavor]
    csv_path = HERE / csv_name
    with csv_path.open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source)
        missing = REQUIRED_COLUMNS.difference(reader.fieldnames or ())
        if missing:
            raise ValueError(f"{csv_name} is missing columns: {', '.join(sorted(missing))}")
        rows = list(reader)

    # Reverse iteration preserves the existing policy: the last export row for
    # duplicate localized names wins.
    by_name = {}
    for row in reversed(rows):
        name = row["Name_lang"]
        display_id = row["DisplayID_0"]
        if not name or not display_id or display_id == "0":
            continue
        by_name.setdefault(name, (row["ID"], display_id))

    lines = [
        "-- This file is auto-generated by creature_parser.py. Do not edit directly.",
        "local _, addon = ...",
        "addon.BanterData.CreatureByName = {",
    ]
    for name, (npc_id, display_id) in by_name.items():
        lines.append(f"    [{lua_string(name)}] = {{ id = {npc_id}, displayId = {display_id} }},")
    lines.extend(["}", ""])
    (HERE / lua_name).write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {lua_name}: {len(by_name)} names from {csv_name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("flavor", choices=(*EXPORTS, "all"), nargs="?", default="all")
    args = parser.parse_args()
    flavors = EXPORTS if args.flavor == "all" else (args.flavor,)
    for flavor in flavors:
        generate(flavor)


if __name__ == "__main__":
    main()
